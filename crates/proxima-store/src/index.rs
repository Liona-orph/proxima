//! [`IndexSpec`] and [`AnyIndex`]: choosing an index at runtime.
//!
//! `proxima-index` deliberately has no enum over its implementations — a
//! library caller knows at compile time which index it wants, and a `dyn
//! VectorIndex` covers the case where it does not. A *server* is the case where
//! it does not, twice over: the index kind arrives in a JSON request body, and
//! it has to survive a round trip through a snapshot header.
//!
//! `Box<dyn VectorIndex>` is not enough for that, because restoring a snapshot
//! and describing a collection both need to know which concrete index is
//! present and to reach past the trait — for `HnswIndex::compact`, for the
//! graph, for the IVF-PQ centroid histogram. So there is an enum, and it lives
//! here rather than in `proxima-index` because it is the storage layer that
//! needs the closed set.

use proxima_core::{Metadata, Result, SearchResult, VectorId, VectorSpace};
use proxima_index::{
    Filter, FlatIndex, HnswConfig, HnswIndex, IndexStats, IvfPqConfig, IvfPqIndex, VectorIndex,
};

/// Which index a collection uses, and how it is configured.
///
/// The persisted form of this is in the snapshot header, so adding a variant is
/// a format change; see [`crate::snapshot`].
#[derive(Debug, Clone, PartialEq)]
pub enum IndexSpec {
    /// Exhaustive scan. Exact, no parameters, and the right answer below a few
    /// tens of thousands of vectors.
    Flat,
    /// The navigable small world graph.
    Hnsw(HnswConfig),
    /// Inverted file over product-quantized residuals.
    IvfPq(IvfPqConfig),
}

impl IndexSpec {
    /// The short name used in JSON, on the command line and in metrics labels.
    pub fn name(&self) -> &'static str {
        match self {
            IndexSpec::Flat => "flat",
            IndexSpec::Hnsw(_) => "hnsw",
            IndexSpec::IvfPq(_) => "ivfpq",
        }
    }

    /// Build an empty index of this kind over `space`.
    pub fn build(&self, space: VectorSpace) -> Result<AnyIndex> {
        Ok(match self {
            IndexSpec::Flat => AnyIndex::Flat(FlatIndex::new(space)),
            IndexSpec::Hnsw(config) => AnyIndex::Hnsw(HnswIndex::new(space, *config)?),
            IndexSpec::IvfPq(config) => AnyIndex::IvfPq(IvfPqIndex::new(space, config.clone())?),
        })
    }
}

/// One of the concrete index implementations.
///
/// Delegates [`VectorIndex`] to whichever it holds. The delegation is written
/// out rather than generated by a macro because there are five methods and one
/// enum, and a macro would trade fifty readable lines for a thing nobody can
/// grep.
#[derive(Debug)]
pub enum AnyIndex {
    /// See [`FlatIndex`].
    Flat(FlatIndex),
    /// See [`HnswIndex`].
    Hnsw(HnswIndex),
    /// See [`IvfPqIndex`].
    IvfPq(IvfPqIndex),
}

impl AnyIndex {
    /// The spec that would rebuild an empty index of this kind.
    pub fn spec(&self) -> IndexSpec {
        match self {
            AnyIndex::Flat(_) => IndexSpec::Flat,
            AnyIndex::Hnsw(index) => IndexSpec::Hnsw(*index.config()),
            AnyIndex::IvfPq(index) => IndexSpec::IvfPq(index.config().clone()),
        }
    }

    /// The short name of the index kind.
    pub fn kind(&self) -> &'static str {
        match self {
            AnyIndex::Flat(_) => "flat",
            AnyIndex::Hnsw(_) => "hnsw",
            AnyIndex::IvfPq(_) => "ivfpq",
        }
    }

    /// The space the index is over.
    pub fn space(&self) -> &VectorSpace {
        match self {
            AnyIndex::Flat(index) => index.space(),
            AnyIndex::Hnsw(index) => index.space(),
            AnyIndex::IvfPq(index) => index.space(),
        }
    }

    /// Metadata for `id`, for a search response that carries it.
    pub fn metadata(&self, id: VectorId) -> Option<&Metadata> {
        match self {
            AnyIndex::Flat(index) => index.metadata(id),
            AnyIndex::Hnsw(index) => index.metadata(id),
            AnyIndex::IvfPq(index) => index.metadata(id),
        }
    }

    /// Reclaim tombstoned slots, if the index has any.
    ///
    /// Returns the number reclaimed, which is always zero for
    /// [`FlatIndex`], because it frees a slot on delete and therefore never
    /// accumulates any.
    pub fn compact(&mut self) -> Result<usize> {
        match self {
            AnyIndex::Flat(_) => Ok(0),
            AnyIndex::Hnsw(index) => index.compact(),
            AnyIndex::IvfPq(index) => index.compact(),
        }
    }
}

impl VectorIndex for AnyIndex {
    fn insert(&mut self, id: VectorId, vector: &[f32], metadata: Metadata) -> Result<()> {
        match self {
            AnyIndex::Flat(index) => index.insert(id, vector, metadata),
            AnyIndex::Hnsw(index) => index.insert(id, vector, metadata),
            AnyIndex::IvfPq(index) => index.insert(id, vector, metadata),
        }
    }

    fn remove(&mut self, id: VectorId) -> Result<()> {
        match self {
            AnyIndex::Flat(index) => index.remove(id),
            AnyIndex::Hnsw(index) => index.remove(id),
            AnyIndex::IvfPq(index) => index.remove(id),
        }
    }

    fn search(&self, query: &[f32], k: usize, filter: &dyn Filter) -> Result<Vec<SearchResult>> {
        match self {
            AnyIndex::Flat(index) => index.search(query, k, filter),
            AnyIndex::Hnsw(index) => index.search(query, k, filter),
            AnyIndex::IvfPq(index) => index.search(query, k, filter),
        }
    }

    fn contains(&self, id: VectorId) -> bool {
        match self {
            AnyIndex::Flat(index) => index.contains(id),
            AnyIndex::Hnsw(index) => index.contains(id),
            AnyIndex::IvfPq(index) => index.contains(id),
        }
    }

    fn len(&self) -> usize {
        match self {
            AnyIndex::Flat(index) => index.len(),
            AnyIndex::Hnsw(index) => index.len(),
            AnyIndex::IvfPq(index) => index.len(),
        }
    }

    fn stats(&self) -> IndexStats {
        match self {
            AnyIndex::Flat(index) => index.stats(),
            AnyIndex::Hnsw(index) => index.stats(),
            AnyIndex::IvfPq(index) => index.stats(),
        }
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use proxima_core::Metric;

    use super::*;

    #[test]
    fn every_spec_builds_and_names_itself() {
        let space = VectorSpace::new(8, Metric::Euclidean).unwrap();
        for spec in [
            IndexSpec::Flat,
            IndexSpec::Hnsw(HnswConfig::new()),
            IndexSpec::IvfPq(IvfPqConfig::new(4, 4)),
        ] {
            let index = spec.build(space.clone()).unwrap();
            assert_eq!(index.kind(), spec.name());
            assert_eq!(index.spec(), spec);
            assert!(index.is_empty());
        }
    }

    #[test]
    fn delegation_reaches_the_inner_index() {
        let space = VectorSpace::new(2, Metric::Euclidean).unwrap();
        let mut index = IndexSpec::Flat.build(space).unwrap();
        index
            .insert(
                VectorId::new(1),
                &[1.0, 0.0],
                Metadata::new().with("tag", "a"),
            )
            .unwrap();
        assert!(index.contains(VectorId::new(1)));
        assert_eq!(index.len(), 1);
        assert_eq!(index.stats().dim, 2);
        assert_eq!(
            index.metadata(VectorId::new(1)).and_then(|m| m.text("tag")),
            Some("a")
        );
        assert_eq!(index.compact().unwrap(), 0);
        index.remove(VectorId::new(1)).unwrap();
        assert!(index.is_empty());
    }
}
